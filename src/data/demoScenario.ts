    coverImage: '',
    regions: ['CN'],
    game: 'ACC',
    carClass: 'GT3',
    defaultRuleset: {
      scoringTable: [
        { position: 1, points: 25 },
        { position: 2, points: 18 },
        { position: 3, points: 15 },
        { position: 4, points: 12 },
        { position: 5, points: 10 },
        { position: 6, points: 8 },
        { position: 7, points: 6 },
        { position: 8, points: 4 },
      ],
      scoringNote_zh: '演示用标准积分表，前 8 名得分。',
      scoringNote_en: 'Demo standard scoring table, points to top 8.',
    },
    rounds: [round],
    createdBy: 'admin1',
