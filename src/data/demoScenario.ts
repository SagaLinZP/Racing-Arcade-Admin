import { competitions, createDefaultGameConfig } from './competitions'
import type { Competition, Round, Stage, Session, Split } from './competitions'
import { registrations } from './registrations'
import type { Registration } from './registrations'
import { protests } from './protests'
import type { Protest } from './protests'
import { serverInstances } from './servers'
import { drivers } from './drivers'
import { bump } from './store'

export const DEMO_COMP_ID = 'demo_comp'
export const DEMO_ROUND_ID = 'demo_comp_r1'
export const DEMO_RACE_STAGE_ID = 'demo_comp_r1_race'
export const DEMO_FINAL_STAGE_ID = 'demo_comp_r1_final'
export const DEMO_RACE_SPLIT_ID = 'demo_comp_r1_race_sp1'
export const DEMO_RACE_SESSION_ID = 'demo_comp_r1_race_se_r'

const DEMO_DRIVER_COUNT = 8
const DEMO_NUMBERS = [7, 23, 14, 88, 11, 5, 44, 3]

function buildSessions(stageId: string): Session[] {
  return [
    { id: `${stageId}_se_p`, type: 'practice', name_zh: '练习赛', name_en: 'Practice', durationMinutes: 20 },
    { id: `${stageId}_se_q`, type: 'qualifying', name_zh: '排位赛', name_en: 'Qualifying', durationMinutes: 15 },
    { id: `${stageId}_se_r`, type: 'race', name_zh: '正赛', name_en: 'Race', raceDuration: 30, raceDurationType: 'time' },
  ]
}

function buildSplit(stageId: string, splitNumber: number, serverName: string): Split {
  return {
    id: `${stageId}_sp${splitNumber}`,
    splitNumber,
    serverName,
    serverPassword: 'demo2026',
    adminPassword: 'admin',
    spectatorPassword: '',
    maxConnections: 30,
    registerToLobby: true,
    udpPort: 9600,
    tcpPort: 9600,
    httpPort: 8081,
    maxCarSlots: 30,
    isRaceLocked: 1,
    dumpLeaderboards: 1,
    dumpEntryList: 1,
  }
}

